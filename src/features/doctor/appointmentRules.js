export const APPOINTMENT_TRANSITIONS = {
  REQUESTED: ['CONFIRMED', 'CANCELLED', 'PROPOSED_NEW_TIME'],
  SCHEDULED: ['CONFIRMED', 'WAITING', 'IN_CONSULTATION', 'COMPLETED', 'NO_SHOW', 'MISSED', 'CANCELLED'],
  CONFIRMED: ['WAITING', 'IN_CONSULTATION', 'COMPLETED', 'NO_SHOW', 'MISSED', 'CANCELLED'],
  WAITING: ['IN_CONSULTATION', 'COMPLETED', 'NO_SHOW'],
  IN_CONSULTATION: ['COMPLETED'],
  MISSED: ['NO_SHOW'],
  PROPOSED_NEW_TIME: ['CONFIRMED', 'CANCELLED'],
  COMPLETED: [],
  NO_SHOW: [],
  CANCELLED: [],
};

export function canTransition(from, to) {
  return APPOINTMENT_TRANSITIONS[from]?.includes(to) ?? false;
}
